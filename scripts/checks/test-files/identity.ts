// The order in which recipes run, and the identity of each generated file: what it would take to make it again.

import { createHash } from 'node:crypto';

import { CIRCULAR_INPUTS, IDENTITY_ALGORITHM, IDENTITY_ENCODING } from './constants.ts';
import type { Recipe } from './recipes.ts';
import { LIST_SEPARATOR } from '../specifications/constants.ts';

/** The recipes with every input before the recipes that use it, or the circle that prevents an order. */
export function generationOrder(recipes: readonly Recipe[]): { order: Recipe[]; problems: string[] } {
  const byPath = new Map(recipes.map((recipe) => [recipe.path, recipe]));
  const placed = new Set<string>();
  const order: Recipe[] = [];
  let remaining = [...recipes];
  while (remaining.length > 0) {
    const ready = remaining.filter((recipe) =>
      recipe.inputs.every((input) => placed.has(input) || !byPath.has(input)),
    );
    if (ready.length === 0) {
      const circle = remaining.map((recipe) => recipe.path).join(LIST_SEPARATOR);
      return { order, problems: [`${CIRCULAR_INPUTS}: ${circle}`] };
    }
    for (const recipe of ready) {
      placed.add(recipe.path);
      order.push(recipe);
    }
    remaining = remaining.filter((recipe) => !placed.has(recipe.path));
  }
  return { order, problems: [] };
}

/** The identity of every recipe in `order`: a digest of its tool, the tool's version, its arguments and the identities
 * of its inputs. A file whose identity is unchanged would be generated byte for byte again, so it never is. */
export function identities(order: readonly Recipe[], versions: ReadonlyMap<string, string>): Map<string, string> {
  const result = new Map<string, string>();
  for (const recipe of order) {
    const description = JSON.stringify([
      recipe.path,
      recipe.tool,
      versions.get(recipe.tool),
      recipe.commandArguments,
      recipe.inputs.map((input) => result.get(input)),
    ]);
    result.set(recipe.path, createHash(IDENTITY_ALGORITHM).update(description).digest(IDENTITY_ENCODING));
  }
  return result;
}
